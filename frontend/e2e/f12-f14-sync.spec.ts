// F12 push · F13 branches · F14 atualizar e conflitos · marcadores de mudança no gutter.
import { test, expect, openProject, openFile, cursorAt, editorValue, a11y, mod } from './helpers'
import type { Page } from '@playwright/test'

const branchButton = (page: Page) => page.getByRole('banner').getByRole('button', { name: /^Branch: / })
const popup = (page: Page) => page.getByRole('dialog', { name: 'Branches' })
const commitPanel = (page: Page) => page.getByRole('region', { name: 'Commit' })

async function openBranches(page: Page) {
  await branchButton(page).click()
  await expect(popup(page)).toBeVisible()
}

test.describe('F13 branches', () => {
  test('F13-H1 criar branch, trocar, ver locais e remotas', async ({ page, fx }) => {
    const dir = fx.seed()
    fx.remote(dir)
    await openProject(page, dir)
    await openBranches(page)
    await expect(popup(page).getByRole('region', { name: 'Locais' })).toContainText('main')
    await expect(popup(page).getByRole('region', { name: 'Remotas' })).toContainText('origin/main')
    await popup(page).getByRole('button', { name: 'Nova branch…' }).click()
    const dlg = page.getByRole('dialog', { name: 'Nova branch' })
    await dlg.getByLabel('Nome da branch').fill('feat/frete')
    await dlg.getByRole('button', { name: 'Criar' }).click()
    await expect(branchButton(page)).toHaveAccessibleName('Branch: feat/frete')
    expect(fx.git(dir, 'branch', '--show-current')).toBe('feat/frete')

    // Voltar para a main pelo popup (as mudanças locais não conflitam: vão junto).
    await openBranches(page)
    await popup(page).getByRole('button', { name: 'Trocar para main' }).click()
    await expect(branchButton(page)).toHaveAccessibleName('Branch: main')
  })

  test('F13-N1 nome de branch inválido mostra o erro', async ({ page, fx }) => {
    await openProject(page, fx.seed())
    await openBranches(page)
    await popup(page).getByRole('button', { name: 'Nova branch…' }).click()
    const dlg = page.getByRole('dialog', { name: 'Nova branch' })
    await dlg.getByLabel('Nome da branch').fill('nome ruim..')
    await dlg.getByRole('button', { name: 'Criar' }).click()
    await expect(dlg.getByText(/nome de branch inválido/)).toBeVisible()
  })

  test('F13-E1 troca com mudanças locais: "Levar as mudanças" e o editor relê o arquivo', async ({ page, fx }) => {
    const dir = fx.seed()
    // A branch feat muda a 1ª linha do README; na main, a mudança local é no fim do arquivo.
    fx.git(dir, 'stash', '-u')
    fx.git(dir, 'switch', '-q', '-c', 'feat')
    fx.write(dir, 'README.md', '# demo-shop (feat)\n\nProjeto de exemplo para desenvolver a IDE.\n')
    fx.git(dir, 'commit', '-qam', 'titulo da feat')
    fx.git(dir, 'switch', '-q', 'main')
    fx.git(dir, 'stash', 'pop', '-q')
    fx.write(dir, 'README.md', '# demo-shop\n\nProjeto de exemplo para desenvolver a IDE.\nLinha nova local.\n')
    await openProject(page, dir)
    await openFile(page, 'README.md')
    await openBranches(page)
    await popup(page).getByRole('button', { name: 'Trocar para feat' }).click()
    const dlg = page.getByRole('dialog', { name: 'Mudanças locais seriam perdidas' })
    await expect(dlg).toContainText('README.md')
    await dlg.getByRole('button', { name: 'Levar as mudanças' }).click()
    await expect(branchButton(page)).toHaveAccessibleName('Branch: feat')
    // O editor mostra as duas coisas: o título da feat e a linha local.
    await expect.poll(() => editorValue(page)).toContain('# demo-shop (feat)')
    expect(await editorValue(page)).toContain('Linha nova local.')
  })

  test('F13-E2 apagar branch e restaurar pelo aviso', async ({ page, fx }) => {
    const dir = fx.seed()
    fx.git(dir, 'branch', 'velha')
    await openProject(page, dir)
    await openBranches(page)
    await popup(page).getByRole('button', { name: 'Ações de velha' }).click()
    await page.getByRole('menuitem', { name: 'Apagar' }).click()
    await expect(page.getByText('Branch velha apagada')).toBeVisible()
    expect(fx.git(dir, 'branch', '--list', 'velha')).toBe('')
    await page.getByRole('button', { name: 'Restaurar' }).click()
    await expect(page.getByText('Branch velha restaurada')).toBeVisible()
    expect(fx.git(dir, 'branch', '--list', 'velha')).toContain('velha')
  })

  test('F13-A11Y popup de branches sem violações', async ({ page, fx }) => {
    const dir = fx.seed()
    fx.remote(dir)
    await openProject(page, dir)
    await openBranches(page)
    expect(await a11y(page)).toEqual([])
  })
})

test.describe('F12 push', () => {
  test('F12-H3 "Commit e push…": commit, diálogo com o commit e push no remoto', async ({ page, fx }) => {
    const dir = fx.seed()
    const bare = fx.remote(dir)
    await openProject(page, dir)
    await page.keyboard.press('Alt+0')
    await commitPanel(page).getByLabel('Mensagem do commit').fill('catálogo: conta produtos')
    await commitPanel(page).getByRole('button', { name: 'Commit e push…' }).click()
    const dlg = page.getByRole('dialog', { name: 'Enviar commits (push)' })
    await expect(dlg.getByRole('region', { name: 'Commits a enviar' })).toContainText('catálogo: conta produtos')
    await dlg.getByRole('button', { name: 'Push', exact: true }).click()
    await expect(page.getByText('Push concluído')).toBeVisible()
    expect(fx.git(bare, 'log', '-1', '--format=%s', 'main')).toBe('catálogo: conta produtos')
  })

  test('F12-E10 push recusado: atualizar com merge e enviar', async ({ page, fx }) => {
    const dir = fx.seed()
    const bare = fx.remote(dir)
    const other = fx.otherClone(bare)
    fx.write(other, 'OUTRO.md', 'da outra pessoa\n')
    fx.git(other, 'add', '-A')
    fx.git(other, 'commit', '-qm', 'outra pessoa')
    fx.git(other, 'push', '-q')
    await openProject(page, dir)
    await page.keyboard.press('Alt+0')
    await commitPanel(page).getByLabel('Mensagem do commit').fill('meu commit')
    await commitPanel(page).getByRole('button', { name: 'Commit e push…' }).click()
    const dlg = page.getByRole('dialog', { name: 'Enviar commits (push)' })
    await dlg.getByRole('button', { name: 'Push', exact: true }).click()
    await expect(dlg.getByText(/Push recusado/)).toBeVisible()
    await dlg.getByRole('button', { name: 'Atualizar (merge)' }).click()
    await expect(dlg.getByText(/Push recusado/)).toBeHidden({ timeout: 30_000 })
    await dlg.getByRole('button', { name: 'Push', exact: true }).click()
    await expect(page.getByText('Push concluído')).toBeVisible()
    expect(fx.git(bare, 'log', '--format=%s', 'main')).toContain('outra pessoa')
    expect(fx.git(bare, 'log', '--format=%s', 'main')).toContain('meu commit')
  })

  test('F12-E11 branch sem remota: push oferece acompanhar', async ({ page, fx }) => {
    const dir = fx.seed()
    const bare = fx.remote(dir)
    fx.git(dir, 'switch', '-q', '-c', 'feat/nova')
    fx.git(dir, 'commit', '-qam', 'na feat')
    await openProject(page, dir)
    await page.keyboard.press(`${mod}+Shift+K`)
    const dlg = page.getByRole('dialog', { name: 'Enviar commits (push)' })
    await expect(dlg.getByLabel('Branch de destino')).toHaveValue('feat/nova')
    await expect(dlg.getByRole('checkbox', { name: /Passar a acompanhar/ })).toBeChecked()
    await dlg.getByRole('button', { name: 'Push', exact: true }).click()
    await expect(page.getByText('Push concluído')).toBeVisible()
    expect(fx.git(bare, 'log', '-1', '--format=%s', 'feat/nova')).toBe('na feat')
    expect(fx.git(dir, 'rev-parse', '--abbrev-ref', '@{u}')).toBe('origin/feat/nova')
  })
})

test.describe('F14 atualizar', () => {
  test('F14-H1 atualizar com conflito: aviso, merge em andamento e abortar', async ({ page, fx }) => {
    const dir = fx.seed()
    const bare = fx.remote(dir)
    const other = fx.otherClone(bare)
    fx.write(other, 'README.md', '# demo-shop da outra pessoa\n')
    fx.git(other, 'commit', '-qam', 'outra')
    fx.git(other, 'push', '-q')
    fx.write(dir, 'README.md', '# demo-shop meu\n')
    fx.git(dir, 'commit', '-qam', 'meu')
    await openProject(page, dir)
    await page.keyboard.press(`${mod}+t`)
    await expect(page.getByText('Atualização parou em conflito')).toBeVisible({ timeout: 30_000 })
    // A lista de conflitos abre sozinha; fechando, o aviso no Commit continua.
    const conflicts = page.getByRole('dialog', { name: /^Conflitos/ })
    await expect(conflicts.getByRole('list', { name: 'Arquivos em conflito' })).toContainText('README.md')
    await conflicts.getByRole('button', { name: 'Fechar' }).click()
    await expect(commitPanel(page).getByText(/Merge em andamento/)).toBeVisible()
    await expect(commitPanel(page).getByRole('group', { name: 'Em conflito' })).toContainText('README.md')
    await commitPanel(page).getByRole('button', { name: 'Abortar' }).click()
    await expect(commitPanel(page).getByText(/Merge em andamento/)).toBeHidden()
    expect(fx.read(dir, 'README.md')).toBe('# demo-shop meu\n')
  })

  test('F14-H2 atualizar traz o commit de outra pessoa e o editor relê', async ({ page, fx }) => {
    const dir = fx.seed()
    const bare = fx.remote(dir)
    const other = fx.otherClone(bare)
    fx.write(other, 'README.md', '# demo-shop\n\nAtualizado por outra pessoa.\n')
    fx.git(other, 'commit', '-qam', 'readme')
    fx.git(other, 'push', '-q')
    await openProject(page, dir)
    await openFile(page, 'README.md')
    await page.keyboard.press(`${mod}+t`)
    await expect(page.getByText('Atualizado.')).toBeVisible({ timeout: 30_000 })
    await expect.poll(() => editorValue(page)).toContain('Atualizado por outra pessoa.')
  })
})

test.describe('Marcadores de mudança no gutter', () => {
  test('F12-E12 linhas adicionadas: marcador, reverter e desfazer', async ({ page, fx }) => {
    const dir = fx.seed() // catalog.go tem 3 linhas a mais que o último commit (func Count)
    await openProject(page, dir)
    await openFile(page, 'internal/catalog/catalog.go')
    const added = page.locator('.goide-vcs-added')
    await expect(added.first()).toBeVisible()
    await added.first().click()
    await page.getByRole('menuitem', { name: /Remover as 3 linhas adicionadas/ }).click()
    await expect.poll(() => editorValue(page)).not.toContain('func Count')
    await expect(added).toHaveCount(0)
    await cursorAt(page, 'package catalog')
    await page.keyboard.press(`${mod}+z`)
    await expect.poll(() => editorValue(page)).toContain('func Count')
  })

  test('F12-E13 linha alterada ganha marcador de modificada e reverte', async ({ page, fx }) => {
    const dir = fx.seed()
    await openProject(page, dir, { trust: false })
    await openFile(page, 'internal/cart/cart.go')
    await cursorAt(page, 'Package cart soma itens')
    await page.keyboard.type(' (editado)')
    const modified = page.locator('.goide-vcs-modified')
    await expect(modified).toHaveCount(1)
    await modified.click()
    await page.getByRole('menuitem', { name: 'Reverter este trecho' }).click()
    await expect.poll(() => editorValue(page)).not.toContain('(editado)')
    await expect(modified).toHaveCount(0)
  })
})
